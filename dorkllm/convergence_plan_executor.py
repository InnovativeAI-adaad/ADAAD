# ── Core Engine ───────────────────────────────────────────────────────────────

class ConvergencePlanExecutor:
    """
    INNOV-88 · CPE — Convergence Plan Executor.

    Reads approved GRPs from the CGR ledger, validates governance seals,
    executes remediation actions through governed dispatcher, and records
    outcomes in an HMAC-SHA-256-chained execution ledger.
    """

    def __init__(self) -> None:
        _DATA_DIR.mkdir(parents=True, exist_ok=True)
        self._ledger: List[dict] = _read_jsonl(_EXEC_LEDGER_PATH)
        self._snapshot: Optional[dict] = _read_json(_CPE_SNAPSHOT_PATH)
        self._exec_ids: set = {r.get("plan_id") for r in self._ledger}  # plan_id idempotency — CPE-DOUBLE-0
        self._tail_hash: str = (
            self._ledger[-1]["chain_hash"] if self._ledger else "GENESIS"
        )

    # ── Chain integrity ───────────────────────────────────────────────────────

    def verify_chain(self) -> Tuple[bool, str]:
        """Verify full HMAC chain integrity — CPE-CHAIN-0."""
        if not self._ledger:
            return True, "ledger_empty"
        prev = "GENESIS"
        for i, entry in enumerate(self._ledger):
            payload = {k: v for k, v in entry.items() if k not in ("chain_hash", "exec_seal")}
            expected = _hmac_digest(_canonical_json(payload) + prev)
            if not hmac.compare_digest(entry["chain_hash"][:24], expected[:24]):
                return False, f"chain_break_at_seq_{i}"
            prev = entry["chain_hash"]
        return True, "chain_valid"

    # ── Snapshot ──────────────────────────────────────────────────────────────

    def get_snapshot(self) -> CPESnapshot:
        """Return current CPE execution snapshot — CPE-PERSIST-0."""
        totals = self._compute_totals()
        snap = CPESnapshot(
            total_plans_executed=totals["executed"],
            total_plans_succeeded=totals["succeeded"],
            total_plans_partial=totals["partial"],
            total_plans_failed=totals["failed"],
            total_plans_rejected=totals["rejected"],
            last_execution_id=self._ledger[-1]["execution_id"] if self._ledger else None,
            last_execution_timestamp=self._ledger[-1]["timestamp_utc"] if self._ledger else None,
            cumulative_invariants_scheduled=totals["invariants_scheduled"],
            cumulative_tests_scheduled=totals["tests_scheduled"],
            snapshot_timestamp=_utc_iso(),
        )
        snap_dict = asdict(snap)
        _CPE_SNAPSHOT_PATH.write_text(
            json.dumps(snap_dict, sort_keys=True, indent=2), encoding="utf-8"
        )
        return snap

    def _compute_totals(self) -> dict:
        counts = {
            "executed": len(self._ledger),
            "succeeded": 0, "partial": 0, "failed": 0, "rejected": 0,
            "invariants_scheduled": 0, "tests_scheduled": 0,
        }
        for entry in self._ledger:
            status = entry.get("status", "")
            if status == _STATUS_SUCCESS:
                counts["succeeded"] += 1
            elif status == _STATUS_PARTIAL:
                counts["partial"] += 1
            elif status == _STATUS_FAILED:
                counts["failed"] += 1
            elif status == _STATUS_REJECTED:
                counts["rejected"] += 1
            for ar in entry.get("action_results", []):
                impact = ar.get("impact_applied", {})
                counts["invariants_scheduled"] += impact.get("invariants_added", 0)
                counts["tests_scheduled"] += impact.get("tests_added", 0)
        return counts

    # ── HUMAN-0 Advisory ──────────────────────────────────────────────────────

    def _emit_advisory(self, plan_id: str, severity: str, dimension: str) -> str:
        """Emit HUMAN-0 ratification advisory — CPE-HUMAN0-0."""
        advisory = {
            "advisory_id": str(uuid.uuid4()),
            "plan_id": plan_id,
            "severity": severity,
            "dimension": dimension,
            "message": (
                f"CRITICAL_PLAN_ADVISORY: Plan {plan_id} targets dimension '{dimension}' "
                f"with severity {severity}. HUMAN-0 ratification required before "
                f"execution proceeds. Governor: {_GOVERNOR}."
            ),
            "timestamp_utc": _utc_iso(),
            "governor": _GOVERNOR,
        }
        _append_jsonl(_ADVISORY_LOG_PATH, advisory)
        return advisory["advisory_id"]

    # ── Outcome Telemetry ─────────────────────────────────────────────────────

    def _emit_outcome(self, record: ExecutionRecord) -> None:
        """Emit outcome telemetry for CAL (INNOV-80) — CPE-AUDIT-0."""
        telemetry = {
            "execution_id": record.execution_id,
            "plan_id": record.plan_id,
            "dimension": record.dimension,
            "status": record.status,
            "outcome_score_delta": record.outcome_score_delta,
            "actions_succeeded": record.actions_succeeded,
            "actions_total": record.actions_total,
            "timestamp_utc": record.timestamp_utc,
            "innov_code": _INNOV_CODE,
        }
        _append_jsonl(_OUTCOME_LOG_PATH, telemetry)

    # ── Execute ───────────────────────────────────────────────────────────────

    def execute(
        self,
        top_n: int = DEFAULT_EXECUTE_N,
        severity_filter: Optional[str] = None,
    ) -> List[ExecutionRecord]:
        """
        Read top-N approved GRPs from CGR ledger, validate seals, execute
        remediation actions, and record outcomes.

        CPE-DOUBLE-0: Skip plans already executed (idempotency).
        CPE-VALIDATE-0: Verify GRP governance seal before dispatch.
        CPE-HUMAN0-0: Emit advisory for CRITICAL plans.
        CPE-HALT-0: First action failure halts plan → PARTIAL/FAILED.
        """
        grps = _read_jsonl(_CGR_LEDGER_PATH)
        if not grps:
            return []

        # Filter and rank (by severity: CRITICAL first, then WARNING, then OK)
        _SEVERITY_ORDER = {"CRITICAL": 0, "WARNING": 1, "OK": 2}
        candidates = []
        for plan in grps:
            if plan.get("plan_id") in self._exec_ids:
                continue  # CPE-DOUBLE-0
            sev = plan.get("plan_severity", "OK")
            if severity_filter and sev != severity_filter:
                continue
            candidates.append(plan)

        candidates.sort(key=lambda p: (
            _SEVERITY_ORDER.get(p.get("plan_severity", "OK"), 9),
            p.get("plan_id", ""),
        ))
        candidates = candidates[:top_n]

        results: List[ExecutionRecord] = []
        for plan in candidates:
            rec = self._execute_plan(plan)
            results.append(rec)
        return results

    def _execute_plan(self, plan: dict) -> ExecutionRecord:
        """Execute a single GRP and record the outcome."""
        plan_id = plan.get("plan_id", str(uuid.uuid4()))
        severity = plan.get("plan_severity", "OK")
        dimension = plan.get("target_dimension", "unknown")
        actions: List[dict] = plan.get("remediation_actions", [])
        execution_id = str(uuid.uuid4())
        advisory_id: Optional[str] = None

        # CPE-DOUBLE-0 — idempotency guard
        if execution_id in self._exec_ids:
            return self._make_rejected(execution_id, plan_id, severity, dimension, "DOUBLE_EXEC")

        # CPE-VALIDATE-0 — verify GRP seal
        seal_ok = _verify_grp_seal(plan)

        # CPE-HUMAN0-0 — advisory before CRITICAL execution
        advisory_emitted = False
        if severity == "CRITICAL":
            advisory_id = self._emit_advisory(plan_id, severity, dimension)
            advisory_emitted = True

        action_results: List[ActionResult] = []
        halted = False
        score_delta = 0.0

        if not seal_ok:
            # Seal mismatch — record rejection, do not dispatch
            status = _STATUS_REJECTED
        else:
            for idx, action in enumerate(actions):
                success, detail, impact = _dispatch_action(action, plan_id)
                ar = ActionResult(
                    action_index=idx,
                    action_type=action.get("action_type", "UNKNOWN"),
                    target_dimension=action.get("target_dimension", dimension),
                    success=success,
                    detail=detail,
                    impact_applied=impact,
                )
                action_results.append(ar)
                if success:
                    score_delta += impact.get("score_delta", 0.02)
                else:
                    halted = True  # CPE-HALT-0
                    break

            total = len(actions)
            succeeded = sum(1 for ar in action_results if ar.success)
            if not action_results:
                status = _STATUS_FAILED
            elif halted:
                status = _STATUS_PARTIAL
            elif succeeded == total:
                status = _STATUS_SUCCESS
            else:
                status = _STATUS_PARTIAL

        # Build ledger entry
        seq = len(self._ledger)
        ts = _utc_iso()
        entry_payload: dict = {
            "execution_id": execution_id,
            "plan_id": plan_id,
            "plan_severity": severity,
            "dimension": dimension,
            "actions_total": len(actions),
            "actions_executed": len(action_results),
            "actions_succeeded": sum(1 for ar in action_results if ar.success),
            "status": status,
            "action_results": [asdict(ar) for ar in action_results],
            "seal_verified": seal_ok,
            "advisory_emitted": advisory_emitted,
            "outcome_score_delta": round(score_delta, 6),
            "timestamp_utc": ts,
            "ledger_seq": seq,
            "prev_chain_hash": self._tail_hash,
            "governor": _GOVERNOR,
            "innov_code": _INNOV_CODE,
        }
        chain_hash = _hmac_digest(_canonical_json(entry_payload) + self._tail_hash)
        exec_seal = _hmac_digest(_canonical_json(entry_payload))
        entry_payload["chain_hash"] = chain_hash
        entry_payload["exec_seal"] = exec_seal

        # CPE-AUDIT-0 — write before returning
        _append_jsonl(_EXEC_LEDGER_PATH, entry_payload)
        self._ledger.append(entry_payload)
        self._exec_ids.add(plan_id)
        self._tail_hash = chain_hash

        # Emit outcome telemetry
        rec = ExecutionRecord(
            execution_id=execution_id,
            plan_id=plan_id,
            plan_severity=severity,
            dimension=dimension,
            actions_total=len(actions),
            actions_executed=len(action_results),
            actions_succeeded=sum(1 for ar in action_results if ar.success),
            status=status,
            action_results=[asdict(ar) for ar in action_results],
            seal_verified=seal_ok,
            advisory_emitted=advisory_emitted,
            outcome_score_delta=round(score_delta, 6),
            timestamp_utc=ts,
            ledger_seq=seq,
            prev_chain_hash=entry_payload["prev_chain_hash"],
            chain_hash=chain_hash,
            exec_seal=exec_seal,
        )
        self._emit_outcome(rec)
        return rec

    def _make_rejected(
        self, execution_id: str, plan_id: str, severity: str, dimension: str, reason: str
    ) -> ExecutionRecord:
        ts = _utc_iso()
        seq = len(self._ledger)
        entry_payload: dict = {
            "execution_id": execution_id,
            "plan_id": plan_id,
            "plan_severity": severity,
            "dimension": dimension,
            "actions_total": 0,
            "actions_executed": 0,
            "actions_succeeded": 0,
            "status": _STATUS_REJECTED,
            "action_results": [],
            "seal_verified": False,
            "advisory_emitted": False,
            "outcome_score_delta": 0.0,
            "timestamp_utc": ts,
            "ledger_seq": seq,
            "prev_chain_hash": self._tail_hash,
            "governor": _GOVERNOR,
            "innov_code": _INNOV_CODE,
            "rejection_reason": reason,
        }
        chain_hash = _hmac_digest(_canonical_json(entry_payload) + self._tail_hash)
        exec_seal = _hmac_digest(_canonical_json(entry_payload))
        entry_payload["chain_hash"] = chain_hash
        entry_payload["exec_seal"] = exec_seal
        _append_jsonl(_EXEC_LEDGER_PATH, entry_payload)
        self._ledger.append(entry_payload)
        self._exec_ids.add(plan_id)
        self._tail_hash = chain_hash
        return ExecutionRecord(
            execution_id=execution_id,
            plan_id=plan_id,
            plan_severity=severity,
            dimension=dimension,
            actions_total=0,
            actions_executed=0,
            actions_succeeded=0,
            status=_STATUS_REJECTED,
            action_results=[],
            seal_verified=False,
            advisory_emitted=False,
            outcome_score_delta=0.0,
            timestamp_utc=ts,
            ledger_seq=seq,
            prev_chain_hash=entry_payload["prev_chain_hash"],
            chain_hash=chain_hash,
            exec_seal=exec_seal,
        )

    # ── Execution history ─────────────────────────────────────────────────────

    def get_execution_history(self, last_n: int = 20) -> List[dict]:
        """Return last N execution records — CPE-PERSIST-0."""
        return self._ledger[-last_n:]
