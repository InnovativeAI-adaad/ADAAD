# ── Helpers ───────────────────────────────────────────────────────────────────

def _utc_iso() -> str:
    """Deterministic UTC timestamp — CPE-DETERM-0."""
    return datetime.now(timezone.utc).isoformat()


def _canonical_json(obj: dict) -> str:
    """Canonical JSON for HMAC computation — CPE-DETERM-0."""
    return json.dumps(obj, sort_keys=True, separators=(",", ":"))


def _hmac_digest(payload: str, key: bytes = _HMAC_KEY) -> str:
    return hmac.new(key, payload.encode(), hashlib.sha256).hexdigest()


def _read_jsonl(path: Path) -> List[dict]:
    if not path.exists():
        return []
    records = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line:
            records.append(json.loads(line))
    return records


def _read_json(path: Path) -> Optional[dict]:
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def _append_jsonl(path: Path, record: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as fh:
        fh.write(json.dumps(record, sort_keys=True) + "\n")


def _verify_grp_seal(plan: dict, key: bytes = b"adaad-cgr-chain-key-v1") -> bool:
    """Verify the GRP governance seal from CGR — CPE-VALIDATE-0."""
    stored_seal = plan.get("plan_seal", "")
    payload_keys = [k for k in sorted(plan.keys()) if k != "plan_seal"]
    payload = {k: plan[k] for k in payload_keys}
    expected = hmac.new(key, _canonical_json(payload).encode(), hashlib.sha256).hexdigest()
    return hmac.compare_digest(stored_seal[:24], expected[:24])


# ── Action Dispatcher ─────────────────────────────────────────────────────────

# Governed action catalogue — deterministic execution stubs (CPE-DETERM-0).
# Each handler returns (success: bool, detail: str, estimated_impact: dict).
def _dispatch_action(action: dict, plan_id: str) -> Tuple[bool, str, dict]:
    """
    Deterministic governed action dispatcher.
    Maps action_type to a governed execution stub that records intent
    without performing live system mutations (sandbox-safe).
    """
    action_type: str = action.get("action_type", "UNKNOWN")
    target: str = action.get("target_dimension", "unknown")
    impact: dict = action.get("impact_estimate", {})

    _DISPATCH_TABLE = {
        "ADD_INVARIANTS": _exec_add_invariants,
        "ADD_TESTS": _exec_add_tests,
        "EMIT_ADVISORY": _exec_emit_advisory,
        "TRIGGER_ASSESSMENT": _exec_trigger_assessment,
        "SCHEDULE_AUDIT": _exec_schedule_audit,
        "ESCALATE_HUMAN0": _exec_escalate_human0,
        "PATCH_DIMENSION_WEIGHT": _exec_patch_dimension_weight,
        "ENABLE_TELEMETRY": _exec_enable_telemetry,
    }

    handler = _DISPATCH_TABLE.get(action_type, _exec_unknown)
    return handler(action_type, target, impact, plan_id)


def _exec_add_invariants(action_type, target, impact, plan_id):
    count = impact.get("invariants_added", 0)
    return True, f"Governed stub: schedule +{count} Hard-class invariants for {target}", impact


def _exec_add_tests(action_type, target, impact, plan_id):
    count = impact.get("tests_added", 0)
    return True, f"Governed stub: schedule +{count} acceptance tests for {target}", impact


def _exec_emit_advisory(action_type, target, impact, plan_id):
    return True, f"Advisory emitted to HUMAN-0 for dimension {target} (plan {plan_id})", impact


def _exec_trigger_assessment(action_type, target, impact, plan_id):
    return True, f"Governed stub: trigger re-assessment cycle for {target}", impact


def _exec_schedule_audit(action_type, target, impact, plan_id):
    return True, f"Governed stub: schedule constitutional audit sweep for {target}", impact


def _exec_escalate_human0(action_type, target, impact, plan_id):
    return True, f"HUMAN-0 escalation recorded for {target} under plan {plan_id}", impact


def _exec_patch_dimension_weight(action_type, target, impact, plan_id):
    return True, f"Governed stub: dimension weight adjustment queued for {target}", impact


def _exec_enable_telemetry(action_type, target, impact, plan_id):
    return True, f"Governed stub: telemetry enablement scheduled for {target}", impact


def _exec_unknown(action_type, target, impact, plan_id):
    return False, f"Unknown action_type '{action_type}' — CPE-HALT-0 triggered", {}


